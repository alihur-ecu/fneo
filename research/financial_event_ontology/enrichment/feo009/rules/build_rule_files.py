def main() -> None:
    for relative, rules in all_rules().items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"rules": rules}, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
        print(f"{relative}: {len(rules)}")


