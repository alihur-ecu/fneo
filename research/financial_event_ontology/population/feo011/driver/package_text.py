"""Assemble the dry-population review package from computed counts."""

from __future__ import annotations


def render_package(stats: dict) -> str:
    """Publication-facing review package. Counts are coverage, not accuracy."""
    readiness = stats["readiness"]
    blockers = stats.get("blockers") or []
    warnings = stats.get("warnings") or []
    lines = [
        "# Dry population review package",
        "",
        "## 1. Task identity",
        "",
        "Task FEO-011 is the first thirty-document dry population of Financial News Event Ontology 0.1.0-rc2.",
        f"Experiment identifier: {stats.get('experiment_id')}.",
        f"Run date: {stats.get('generated_at')}.",
        "The population is a candidate inventory for manual review. It does not report an accuracy score, and competency-question rows are not final results.",
        "",
        "## 2. Ontology and adapter versions",
        "",
        f"Ontology: Financial News Event Ontology 0.1.0-rc2. SHA-256 `{stats.get('ontology_sha256')}`.",
        f"Corrected adapter: {stats.get('adapter_version')}.",
        f"Mapping version: {stats.get('mapping_version')}. Enrichment rule version: {stats.get('rule_version')}.",
        "The ontology release candidate, the enrichment rules, and the corrected adapter were not modified.",
        "The provisional namespace `https://w3id.org/fneo/` was not registered.",
        "",
        "## 3. Graph safety",
        "",
        f"Endpoint: {stats.get('endpoint')}.",
        f"Frozen run: {stats.get('frozen_run')}.",
        "Container identity: financial-event-ontology-neo4j-full, image neo4j:5.9, running. The population connected only to bolt://127.0.0.1:17688.",
        "Reads used read transactions and the corrected adapter's query guard. The development endpoint on port 7687 was rejected by that guard.",
        "The database password is not recorded in this package.",
        "",
        "## 4. Document inventory",
        "",
        f"Canonical inventory size: {stats.get('inventory_count')}.",
        f"Documents processed: {stats.get('documents_processed')}.",
        f"Status counts: {stats.get('status_counts')}.",
        "Selection did not depend on expected enrichment yield. Order follows the canonical inventory.",
        "",
        "## 5. Extraction summary",
        "",
        f"Source records: {stats.get('source_records')}.",
        "Each document was extracted separately. A document failure does not rewrite another document's records.",
        "",
        "## 6. Candidate summary",
        "",
        f"Candidates: {stats.get('candidates')}.",
        f"Schema-invalid candidates excluded from the engine: {stats.get('invalid_candidates')}.",
        "",
        "## 7. Decision summary",
        "",
        f"Decisions: {stats.get('decisions')}.",
        f"Accepted: {stats.get('accepted')}.",
        f"Review-required: {stats.get('review_required')}.",
        f"Rejected: {stats.get('rejected')}.",
        f"Insufficient evidence: {stats.get('insufficient_evidence')}.",
        f"Out of scope: {stats.get('out_of_scope')}.",
        f"Suppressed: {stats.get('suppressed')}.",
        "",
        "## 8. Profile separation",
        "",
        "Accepted core RDF contains CORE_DETERMINISTIC decisions that the engine marked accepted and direct-triple eligible.",
        "EXTENSION_REVIEWED, CANDIDATE_REVIEW, and EXPERIMENTAL_TEMPORAL outputs are separate graphs.",
        "Review, rejected, and suppressed decisions do not receive a positive direct semantic triple.",
        "No candidate or experimental fact was written into the accepted core graph by the profile filter.",
        f"Profile decision counts: {stats.get('profile_counts')}.",
        "",
        "## 9. Entity population",
        "",
        f"MarketIndex accepted / review-required: {stats.get('market_index')}.",
        f"EquityMarket accepted / review-required: {stats.get('equity_market')}.",
        f"CentralBank, CommercialBank, Currency, EquityShare, FinancialSystem, FinancialSector: {stats.get('extension_entities')}.",
        "These tallies are population counts. They are not accuracy.",
        "",
        "## 10. Event population",
        "",
        f"MarketChangeEvent primary / sensitivity / other: {stats.get('market_change_kinds')}.",
        f"MarketChangeEvent accepted / review-required / rejected / insufficient: {stats.get('market_change_status')}.",
        "An earlier elicitation described 25 primary events across 18 documents. That figure is reference evidence, not a target quota, and it is not treated here as a defect when the count differs.",
        "",
        "## 11. Affected-market population",
        "",
        f"hasAffectedMarket accepted / review-required: {stats.get('affected_market')}.",
        "",
        "## 12. Temporal population",
        "",
        f"Accepted explicit hasEventTime decisions: {stats.get('accepted_event_time')}.",
        f"Review-required hasEventTime decisions: {stats.get('review_event_time')}.",
        f"Source TLINK rows: {stats.get('tlink_count')}. These rows are not accepted temporal facts.",
        "Rule-attached anchors were not materialised as accepted event time.",
        "Direct event-time anchoring is reported separately from event-to-event ordering.",
        "",
        "## 13. Value population",
        "",
        f"NumericalValue / PercentageValue / MonetaryAmount / QuantityValue decisions: {stats.get('values')}.",
        f"Accepted event-value links: {stats.get('accepted_event_value_links')}.",
        "Values may be materialised independently. Co-presence was not converted into an event-value relation.",
        "",
        "## 14. Evidence traceability",
        "",
        "Accepted assertions were counted separately for entity type, event type, affected market, event time, value type, and temporal order.",
        f"Accepted financial assertions missing source document, textual evidence, or rule identifier: {stats.get('missing_financial_evidence')}.",
        "No single percentage combines those categories.",
        "",
        "## 15. SHACL results",
        "",
        f"Consolidated accepted core conforms: {stats.get('shacl_conforms')}.",
        f"Consolidated violations / warnings / information: {stats.get('shacl_counts')}.",
        f"Per-document core violations that excluded a document from the release-eligible graph: {stats.get('shacl_exceptions')}.",
        "Extension shapes were applied only to the extension-profile graph.",
        "pySHACL is not installed. The local shape checker is the only engine used. Independent confirmation remains a pre-release condition. Violations were not reclassified as warnings.",
        "",
        "## 16. Reasoner results",
        "",
        "No project-local reasoner was available. Consistency and unsatisfiable classes were not computed. No inferred triple was counted as an extracted fact.",
        "",
        "## 17. Competency-question preview",
        "",
        "Approved queries FCQ-001 through FCQ-010, FDQ-001 through FDQ-005, FDQ-006, and FDQ-008 were executed as previews when the query file was present.",
        "FDQ-008 is a co-presence demonstration and carries an explicit warning.",
        "Temporal extension queries were executed only against accepted extension temporal facts.",
        f"Preview execution statuses: {stats.get('cq_status_counts')}.",
        "Manual correctness is not evaluated. These rows are not final competency-question results.",
        "",
        "## 18. Review package",
        "",
        f"Primary market-change rows: {stats.get('primary_events')} across {stats.get('primary_documents')} documents.",
        f"Extension sample documents: {stats.get('extension_documents')}.",
        f"Rejected-sample rows: {stats.get('rejected_rows')}.",
        f"Temporal-sample rows: {stats.get('temporal_rows')}.",
        "Review labels and reviewer notes were left blank.",
        "",
        "## 19. Mapping coverage",
        "",
        "Coverage by target class and property is in `evaluation/population_coverage.csv`.",
        "The table records candidate, accepted, review, rejected, and insufficient counts. It does not record correctness.",
        "",
        "## 20. Adapter gaps",
        "",
        f"Gap counts by severity: {stats.get('gap_severity')}.",
        "No adapter change was applied.",
        "",
        "## 21. Rule-change proposals",
        "",
        f"Proposals recorded: {stats.get('proposals')}. None were applied.",
        "",
        "## 22. Determinism",
        "",
        f"Determinism: {stats.get('determinism')}.",
        "Two complete passes were compared on source records, candidates, decisions, public IRIs, and RDF graphs. Manifest timestamps were not required to match.",
        "",
        "## 23. Graph immutability",
        "",
        f"Nodes before / after: {stats.get('nodes_before')} / {stats.get('nodes_after')}.",
        f"Relationships before / after: {stats.get('relationships_before')} / {stats.get('relationships_after')}.",
        f"AnnotatedText before / after: {stats.get('documents_before')} / {stats.get('documents_after')}.",
        "",
        "## 24. Limitations",
        "",
        "The dry population does not establish that an accepted triple is correct.",
        "Extension entity classes were not populated when their rules do not consume the profile requested by the corrected adapter.",
        "Ordering relations remain source inventory unless the unchanged adapter emits a candidate and the engine accepts it.",
        "Only one SHACL checker was available. No OWL reasoner was available.",
        "Cross-document surface-form matches are listed as future identity candidates and were not asserted.",
        "",
        "## 25. Readiness for manual review",
        "",
        f"Readiness: {readiness}.",
        "",
    ]
    if blockers:
        lines.append("Blocking conditions:")
        lines.append("")
        for item in blockers:
            lines.append(f"- {item}")
        lines.append("")
    if warnings:
        lines.append("Warnings that do not by themselves block review preparation:")
        lines.append("")
        for item in warnings:
            lines.append(f"- {item}")
        lines.append("")
    lines.extend(
        [
            "## 26. Files created",
            "",
            "Outputs are under `research/financial_event_ontology/population/feo011/`.",
            "They include per-document extraction, candidates, decisions, accepted core RDF, review-required RDF, rejected records, experimental temporal RDF, SHACL reports, competency-question previews, and the review tables.",
            "",
            "## 27. Recommended next task",
            "",
            "FEO-012 should be the manual review of this package, using the blank review labels.",
            "That review should not be replaced by another unattended population, and it should not treat these counts as accuracy.",
            "",
        ]
    )
    return "\n".join(lines) + "\n"
